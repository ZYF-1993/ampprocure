export const JYINS_BASE_ROUTE_COUNT = JYINS_BASE_PATHS.length
export const JYINS_TOTAL_ROUTE_COUNT = JYINS_BASE_PATHS.length * (JYINS_LOCALES.length + 1)

const localeSet = new Set<string>(JYINS_LOCALES)
const basePathSet = new Set<string>(JYINS_BASE_PATHS as readonly string[])

export function normalizePath(pathname: string): string {
  if (!pathname) return '/'
  const hashless = pathname.split('#')[0] ?? pathname
  const queryless = hashless.split('?')[0] ?? hashless
  let normalized = queryless.startsWith('/') ? queryless : '/' + queryless
  if (normalized.length > 1 && normalized.endsWith('/')) normalized = normalized.slice(0, -1)
  return normalized
}

export function stripLocalePrefix(pathname: string): { locale: string | null; basePath: string } {
  const normalized = normalizePath(pathname)
  if (normalized === '/') return { locale: null, basePath: '/' }
  const segments = normalized.slice(1).split('/')
  const maybeLocale = segments[0] ?? null
  if (!maybeLocale || !localeSet.has(maybeLocale)) return { locale: null, basePath: normalized }
  if (segments.length === 1) return { locale: maybeLocale, basePath: '/' }
  return { locale: maybeLocale, basePath: '/' + segments.slice(1).join('/') }
}

export function isJyinsMirroredPath(pathname: string): boolean {
  const normalized = normalizePath(pathname)
  if (basePathSet.has(normalized)) return true
  const parts = stripLocalePrefix(normalized)
  return basePathSet.has(parts.basePath)
}

export function toRouteTitle(pathname: string): string {
  const parts = stripLocalePrefix(pathname)
  const label = parts.basePath === '/' ? 'Homepage Framework' : parts.basePath.split('/').filter(Boolean).join(' / ')
  return parts.locale ? parts.locale.toUpperCase() + ' | ' + label : label
}

export function buildLocalizedPath(basePath: string, locale: string): string {
  const normalizedBase = normalizePath(basePath)
  const normalizedLocale = locale.toLowerCase()
  if (!localeSet.has(normalizedLocale)) return normalizedBase
  if (normalizedBase === '/') return '/' + normalizedLocale
  return '/' + normalizedLocale + normalizedBase
}
