function normalizeLanguage(input: string | null | undefined): SiteLanguage {
  if (!input) {
    return DEFAULT_LANGUAGE
  }

  const lower = input.toLowerCase()
  if (SUPPORTED_LANGUAGES.includes(lower as SiteLanguage)) {
    return lower as SiteLanguage
  }

  return DEFAULT_LANGUAGE
}

export function getStoredLanguage(): SiteLanguage {
  if (typeof window === 'undefined') {
    return DEFAULT_LANGUAGE
  }

  try {
    return normalizeLanguage(window.localStorage.getItem(SITE_LANGUAGE_STORAGE_KEY))
  } catch {
    return DEFAULT_LANGUAGE
  }
}

export async function initI18n() {
  if (!i18next.isInitialized) {
    await i18next.init({
      lng: getStoredLanguage(),
      fallbackLng: DEFAULT_LANGUAGE,
      debug: false,
      interpolation: {
        escapeValue: false,
      },
      resources: LANGUAGE_RESOURCES,
      defaultNS: 'common',
      ns: ['common'],
      returnEmptyString: false,
    })
  }

  return i18next
}

export function t(key: string, defaultValue?: string) {
  if (!i18next.isInitialized) {
    return defaultValue ?? key
  }

  return i18next.t(key, { defaultValue }) as string
}

export async function setSiteLanguage(nextLanguage: SiteLanguage) {
  const normalized = normalizeLanguage(nextLanguage)
  const instance = await initI18n()
  await instance.changeLanguage(normalized)

  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(SITE_LANGUAGE_STORAGE_KEY, normalized)
    } catch {
      // ignore storage write errors
    }
  }

  if (typeof document !== 'undefined') {
    document.documentElement.lang = normalized
  }
}

export function getCurrentLanguage(): SiteLanguage {
  return normalizeLanguage(i18next.language)
}
